#!/usr/bin/env python3
"""Style names for the app: checks the ARB files against the catalog and
writes lib/l10n/style_names.dart (id -> AppLocalizations getter).

The style catalog (packages/tsumiki_shared/lib/catalogs/restyle_styles.dart)
keeps one English `label` per style, the neutral name other clients read.
What the app shows comes from lib/l10n/app_<locale>.arb, key `style` + the
id in lowerCamelCase (`cave-painting` -> `styleCavePainting`). A new style
needs a name in every ARB file, then:

    python3 tools/gen_style_l10n.py && flutter gen-l10n
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "packages/tsumiki_shared/lib/catalogs/restyle_styles.dart"
L10N = ROOT / "lib/l10n"
OUT = L10N / "style_names.dart"


def key(style_id: str) -> str:
    parts = re.split(r"[^a-zA-Z0-9]+", style_id)
    return "style" + "".join(p[:1].upper() + p[1:] for p in parts if p)


def catalog_ids() -> list[str]:
    ids = re.findall(r"RestyleStyle\(\s*id: '([^']+)'", CATALOG.read_text())
    if len(ids) != len(set(ids)):
        sys.exit("duplicate style ids in the catalog")
    return ids


def main() -> None:
    ids = catalog_ids()
    keys = {i: key(i) for i in ids}
    if len(set(keys.values())) != len(ids):
        sys.exit("two style ids map to the same ARB key")
    missing = []
    for arb in sorted(L10N.glob("app_*.arb")):
        names = json.loads(arb.read_text())
        missing += [f"{arb.name}: {k} ({i})" for i, k in keys.items() if not names.get(k)]
        extra = [k for k in names if k.startswith("style") and k not in keys.values()]
        missing += [f"{arb.name}: {k} has no style in the catalog" for k in extra]
    if missing:
        sys.exit("\n".join(missing))
    cases = "\n".join(f"    '{i}' => l.{k}," for i, k in keys.items())
    OUT.write_text(
        "// GENERATED by tools/gen_style_l10n.py from the style catalog. Do not edit.\n"
        "\n"
        "import 'package:tsumiki_shared/tsumiki_shared.dart';\n"
        "\n"
        "import 'app_localizations.dart';\n"
        "\n"
        "/// The style's name in the app's language; an id the ARB files do not\n"
        "/// know falls back to the catalog's English label, then to the id.\n"
        "String styleName(AppLocalizations l, String id) => switch (id) {\n"
        f"{cases}\n"
        "    _ => restyleStyleById(id)?.label ?? id,\n"
        "  };\n"
    )
    print(f"{len(ids)} styles -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
