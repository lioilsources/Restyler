#!/usr/bin/env python3
"""Writes fixture.g.dart for the device gate: a source photo and its class maps
from the PyTorch reference, computed the way ComfyUI does (parity.py).

    python make_fixture.py --face <segformer_face> --clothes <segformer_clothes> \
        --src MangaPrompts/tgbot/tools/bench/srcs/w-glasses.png

Run it in the MangaPrompts/tools/ondevice venv: Pillow must stay 12.1.1.
"""
import argparse
import base64
import io
from pathlib import Path

import numpy as np
import torch
from PIL import Image
from torchvision import transforms
from transformers import AutoModelForSemanticSegmentation

RESIZE = transforms.Resize((512, 512))
TO_TENSOR = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225]),
])


def class_map(model_dir: str, im: Image.Image) -> str:
    model = AutoModelForSemanticSegmentation.from_pretrained(model_dir).eval()
    with torch.no_grad():
        logits = model(pixel_values=TO_TENSOR(RESIZE(im)).unsqueeze(0)).logits
    up = torch.nn.functional.interpolate(
        logits, size=(im.height, im.width), mode="bilinear", align_corners=False)
    out = io.BytesIO()
    Image.fromarray(up.argmax(1)[0].numpy().astype(np.uint8)).save(out, "PNG", optimize=True)
    return base64.b64encode(out.getvalue()).decode()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--face", required=True)
    ap.add_argument("--clothes", required=True)
    ap.add_argument("--src", required=True)
    args = ap.parse_args()
    src = Path(args.src).read_bytes()
    im = Image.open(io.BytesIO(src)).convert("RGB")
    Path(__file__).with_name("fixture.g.dart").write_text(
        "// Generated by make_fixture.py, do not edit.\n"
        "// ignore_for_file: lines_longer_than_80_chars\n"
        f"const kSourcePng = '{base64.b64encode(src).decode()}';\n"
        f"const kGoldenFacePng = '{class_map(args.face, im)}';\n"
        f"const kGoldenClothesPng = '{class_map(args.clothes, im)}';\n"
    )


if __name__ == "__main__":
    main()
